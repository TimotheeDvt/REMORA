#include "DSP/Graph/NodeTypeRegistry.h"
#include "DSP/Graph/Presets/AllPresets.h"
#include <JuceHeader.h>
#include <iostream>
#include <set>

// Builds every preset graph and prints its node composition, so the NIME paper's preset table
// (papers/nime/preset-table.tex) is regenerated from the code rather than edited by hand.
// Usage: REMORAPresetStats [table-output.tex]   (summary always goes to stdout)
namespace {

using Graph::NodeCategory;

struct PresetEntry {
    const char* name;
    std::unique_ptr<Graph::NodeGraph> (*build)();
    bool handCodedPrecursor; // was a hand-written C++ mapping class before the graph engine
    bool inSelector;         // surfaced in the plugin's preset selector (see SynthManager's constructor)
};

const PresetEntry kPresets[] = {
    { "Simple",              Graph::Presets::buildSimple,          true,  true  },
    { "Wind Noise",          Graph::Presets::buildWindNoise,       false, true  },
    { "Bowed Chord",         Graph::Presets::buildBowedChord,      true,  true  },
    { "Lead+Drone",          Graph::Presets::buildLeadDrone,       true,  true  },
    { "Spin Filter",         Graph::Presets::buildSpinFilter,      true,  false },
    { "Martial Effort",      Graph::Presets::buildMartialEffort,   true,  false },
    { "Martial Momentum",    Graph::Presets::buildMartialMomentum, true,  true  },
    { "Azimut",              Graph::Presets::buildAzimut,          true,  false },
    { "Azimut+",             Graph::Presets::buildAzimutPlus,      true,  false },
    { "Azimut Reverb",       Graph::Presets::buildAzimutReverb,    true,  false },
    { "Azimut Kinetic",      Graph::Presets::buildAzimutKinetic,   false, true  },
    { "Speed Gate",          Graph::Presets::buildSpeedGate,       true,  true  },
    { "Spin Voices",         Graph::Presets::buildSpinVoice,       true,  false },
    { "Spin Voices (Scale)", Graph::Presets::buildSpinVoiceScale,  false, true  },
    { "Vocal Tract",         Graph::Presets::buildVocalTract,      false, true  },
};

const char* categoryName(NodeCategory c) {
    switch (c) {
        case NodeCategory::Source:  return "source";
        case NodeCategory::Math:    return "math";
        case NodeCategory::Sink:    return "sink";
        case NodeCategory::Display: return "display";
    }
    return "?";
}

void printTypeBreakdown(const char* label, const std::set<juce::String>& typeIds) {
    const auto& registry = Graph::NodeTypeRegistry::instance();
    int perCategory[4] = {};
    for (const auto& id : typeIds)
        if (const auto* info = registry.find(id))
            ++perCategory[static_cast<int>(info->category)];
    std::cout << label << ": " << typeIds.size() << " distinct types ("
              << perCategory[0] << " source, " << perCategory[1] << " math, "
              << perCategory[2] << " sink, " << perCategory[3] << " display)\n";
}

} // namespace

int main(int argc, char* argv[]) {
    const auto& registry = Graph::NodeTypeRegistry::instance();

    int registered[4] = {};
    for (const auto& info : registry.all())
        ++registered[static_cast<int>(info.category)];
    std::cout << "Registered node types: " << registry.all().size() << " ("
              << registered[0] << " source, " << registered[1] << " math, "
              << registered[2] << " sink, " << registered[3] << " display)\n\n";

    juce::String table;
    table << "% Generated by software/Tools/PresetStats.cpp (make preset-stats) - do not edit by hand.\n"
          << "\\begin{tabular}{@{}lrrrrr@{}}\n\\toprule\n"
          << "Preset & Nodes & Source & Math & Sink & Display \\\\\n\\midrule\n";

    std::set<juce::String> usedByPrecursors, usedByAll;
    for (const auto& p : kPresets) {
        auto graph = p.build();
        const Graph::NodeCounts c = graph->countNodesByCategory();
        for (const auto& n : graph->nodes()) {
            usedByAll.insert(n.typeId);
            if (p.handCodedPrecursor)
                usedByPrecursors.insert(n.typeId);
        }

        std::cout << juce::String(p.name).paddedRight(' ', 20) << " total " << c.total
                  << "  source " << c.source << "  math " << c.math << "  sink " << c.sink
                  << "  display " << c.display
                  << (p.handCodedPrecursor ? "  [ported]" : "  [graph-native]")
                  << (p.inSelector ? "  [selector]" : "") << "\n";

        juce::String marks;
        if (!p.handCodedPrecursor)
            marks << "\\ast";
        if (p.inSelector)
            marks << "\\dagger";
        juce::String name(p.name);
        if (marks.isNotEmpty())
            name << "$^{" << marks << "}$";
        table << name << " & " << c.total << " & " << c.source << " & " << c.math << " & "
              << c.sink << " & " << c.display << " \\\\\n";
    }
    table << "\\bottomrule\n\\end{tabular}\n";

    std::cout << "\n";
    printTypeBreakdown("Used by the ported (hand-coded precursor) presets", usedByPrecursors);
    printTypeBreakdown("Used by all presets", usedByAll);

    std::cout << "\nRegistered but unused by any preset:";
    for (const auto& info : registry.all())
        if (usedByAll.count(info.id) == 0)
            std::cout << " " << info.id << " (" << categoryName(info.category) << ")";
    std::cout << "\n";

    if (argc > 1) {
        const juce::File out = juce::File::getCurrentWorkingDirectory().getChildFile(argv[1]);
        if (!out.replaceWithText(table)) {
            std::cerr << "Could not write " << out.getFullPathName() << "\n";
            return 1;
        }
        std::cout << "\nWrote " << out.getFullPathName() << "\n";
    } else {
        std::cout << "\n" << table;
    }
    return 0;
}
